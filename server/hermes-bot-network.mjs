import { hobEnv } from './hob-config.mjs';
import { randomBytes } from 'node:crypto';
import { constants } from 'node:fs';
import { lstat, mkdir, open, realpath, rename, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { hermesProfile } from './hermes-client.mjs';

// HOB's bot-to-bot network is intentionally made of two ordinary files in each
// bot's own workspace: a small relay client and a managed block in AGENTS.md.
// Hermes already loads AGENTS.md from the working directory, so every bot gets
// the whole roster without HOB patching the runtime or injecting a private MCP
// server. The managed block is delimited so an operator's own notes survive.

const START = '<!-- HOB:BOT-ROSTER:START -->';
const END = '<!-- HOB:BOT-ROSTER:END -->';

const text = value => typeof value === 'string' ? value.replace(/\s+/g, ' ').trim() : '';
/** Keep user labels from terminating or nesting the managed comment block. */
const blockText = value => text(value).replace(/<!--|-->/g, ' ').replace(/\s+/g, ' ').trim();
const label = bot => blockText(bot.displayName || bot.display_name || bot.bot_title) || (bot.name === 'default' ? 'Main' : bot.name);

/** Native bots share the app's network namespace. A public proxy URL (or a
 * host-published test port) is not the listener inside that namespace. Remote
 * execution backends may explicitly provision their own reachable relay URL.
 */
export function botRelayUrl(env = process.env) {
  env = hobEnv(env);
  const port = Number(env.HOB_PORT || 3000);
  if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error('Invalid app listener port for bot relay.');
  const url = new URL(env.HOB_BOT_RELAY_URL || `http://127.0.0.1:${port}/api/hermes/bot-relay`);
  if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password || url.search || url.hash) throw new Error('Invalid bot relay URL.');
  return url.toString();
}

/** The relay client is installed into a bot workspace and reads its own key. */
function talkClient(endpoint) {
  return String.raw`#!/usr/bin/env node
// HOB bot relay client. Generated by hob; do not store credentials here.
import { randomUUID } from 'node:crypto';
import { constants } from 'node:fs';
import { open } from 'node:fs/promises';
const endpoint = ${JSON.stringify(endpoint)};
// Hermes deliberately removes listener secrets from terminal subprocesses.
// This separate key grants relay access only and survives that environment filter.
let token = process.env.HOB_TALK_TOKEN;
if (!token) {
  let handle;
  try {
    handle = await open(new URL('./relay.json', import.meta.url), constants.O_RDONLY | (constants.O_NOFOLLOW || 0));
    const info = await handle.stat();
    if (!info.isFile() || info.nlink !== 1 || info.size > 4096) throw new Error('Invalid relay credential file.');
    const bytes = Buffer.alloc(4097);
    const { bytesRead } = await handle.read(bytes, 0, bytes.length, 0);
    if (bytesRead > 4096) throw new Error('Invalid relay credential file.');
    const data = JSON.parse(bytes.subarray(0, bytesRead).toString('utf8'));
    if (data.version === 1 && /^[a-f0-9]{64}$/.test(data.token || '')) token = data.token;
  } catch { /* Report a repairable missing credential without leaking file contents. */ }
  finally { await handle?.close(); }
}
const usage = 'Usage: node .hob/talk.mjs roster\n       node .hob/talk.mjs send <bot-id-or-name> <message> [--parent <exchange-id>]\n       node .hob/talk.mjs status <exchange-id>';
let lastRequestId;
if (!token) {
  console.error('This bot has no relay credential. Ask the operator to re-run bot synchronization.');
  process.exit(2);
}
const waitMs = Number(process.env.HOB_TALK_WAIT_MS || 120000);
async function call(pathname, init = {}) {
  const response = await fetch(endpoint + pathname, {
    ...init,
    headers: { 'content-type': 'application/json', authorization: 'Bearer ' + token },
    signal: AbortSignal.timeout(Math.max(1000, Math.min(600000, waitMs + 30000))),
  });
  const body = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(body.error || ('The HOB relay refused the request (' + response.status + ').'));
  return body;
}
const [command, ...args] = process.argv.slice(2);
const parentIndex = args.indexOf('--parent');
const parentExchangeId = parentIndex >= 0 ? args.splice(parentIndex, 2)[1] : undefined;
try {
  if (command === 'roster') {
    const body = await call('/roster');
    for (const bot of body.bots || []) {
      console.log((bot.id === body.self ? '* ' : '  ') + bot.name + ' [' + bot.id + ']' + (bot.main ? ' (Main coordinator)' : '') + (bot.description ? ' — ' + bot.description : ''));
    }
  } else if (command === 'send') {
    if (args.length < 2) throw new Error(usage);
    lastRequestId = process.env.HOB_TALK_REQUEST_ID || randomUUID();
    console.error('Relay request: ' + lastRequestId);
    const body = await call('/send', { method: 'POST', body: JSON.stringify({ to: args[0], message: args.slice(1).join(' '), waitMs, requestId: lastRequestId, sourceSession: process.env.HERMES_UI_SESSION_ID || process.env.HERMES_SESSION_ID || undefined, parentExchangeId }) });
    console.log('Exchange: ' + body.id + ' (' + body.status + ')');
    if (typeof body.reply === 'string' && body.reply.trim()) console.log(body.reply);
    else console.log('Message accepted by ' + (body.toName || body.to) + '. Read its status with: node .hob/talk.mjs status ' + body.id + '. The exchange is also visible in both bot chats.');
  } else if (command === 'status') {
    const body = await call('/exchanges/' + encodeURIComponent(args[0] || ''));
    console.log(JSON.stringify(body, null, 2));
  } else {
    console.log(usage);
    process.exitCode = command ? 2 : 0;
  }
} catch (error) {
  console.error(error.message);
  if (lastRequestId) console.error('If admission is uncertain, retry the same message with HOB_TALK_REQUEST_ID=' + lastRequestId + ' to avoid duplicate work.');
  process.exitCode = 1;
}
`;
}

const managedBlock = (self, roster) => {
  const main = self.name === 'default';
  const lines = [
    START,
    '## HOB bot network',
    '',
    `You are ${label(self)} (stable id: \`${self.name}\`).${main ? ' You are the main coordinator for the other bots.' : ''}`,
    '',
    'The complete HOB roster is:',
    '',
    ...roster.map(bot => `- ${label(bot)} — id: \`${bot.name}\`${bot.name === 'default' ? ' (Main coordinator)' : ''}${bot.tags?.length ? ` [${bot.tags.map(blockText).join(', ')}]` : ''}${blockText(bot.description) ? ` — ${blockText(bot.description)}` : ''}`),
    '',
    'Use the terminal to talk to another bot through HOB:',
    '',
    '```sh',
    'node .hob/talk.mjs roster',
    'node .hob/talk.mjs send <bot-id> "<message>"',
    '```',
    '',
    main
      ? 'You may message any active bot. Delegate clear, self-contained work, include the outcome you need, and wait for the reply before reporting success. Treat a bot reply as that bot’s own work, not as your own.'
      : 'You may contact any active teammate directly when its role fits the work. Keep the main coordinator (`default`) informed of blockers and results. Return results to the calling bot through your normal reply; never start a circular exchange.',
    'Each send creates a separate, inspectable exchange and native conversation. The recipient receives only the context you send. For further delegation from an exchange, include --parent <exchange-id> from its request. Never delegate back to an ancestor. Do not claim a timed-out exchange failed; use node .hob/talk.mjs status <exchange-id> to check it. Use independent tasks for parallel delegation. For recurring work, use Hermes native scheduled jobs; no schedule exists until Hermes confirms it.',
    'The relay is a real message to another bot, which acts with its own tools, workspace, memory and approvals. Never claim another bot completed work without its reply. Do not send secrets, credentials, or tokens through bot messages.',
    'Save final deliverables under artifacts/ in your assigned workspace. Copy completed scratch outputs there before reporting delivery, and link the actual saved file. Keep intermediate files separate. Match the user’s requested language in replies and conversation titles; use the conversation language for Roman Urdu and mixed-language chats, and do not import another bot or project’s language preference.',
    END,
  ];
  return lines.join('\n');
};

async function atomicWrite(filename, value, mode) {
  const temporary = `${filename}.${randomBytes(8).toString('hex')}.tmp`;
  try {
    await writeFile(temporary, value, { flag: 'wx', mode, flush: true });
    await rename(temporary, filename);
  } finally {
    await unlink(temporary).catch(error => { if (error.code !== 'ENOENT') throw error; });
  }
}

async function readAgents(filename) {
  let handle;
  try {
    const entry = await lstat(filename);
    if (!entry.isFile() || entry.isSymbolicLink() || entry.nlink !== 1 || entry.size > 512 * 1024) throw new Error('AGENTS.md must be an independent regular file under 512 KB.');
    handle = await open(filename, constants.O_RDONLY | (constants.O_NOFOLLOW || 0));
    const info = await handle.stat();
    if (!info.isFile() || info.nlink !== 1 || info.dev !== entry.dev || info.ino !== entry.ino) throw new Error('AGENTS.md changed before synchronization.');
    const bytes = Buffer.alloc(512 * 1024 + 1);
    let size = 0;
    while (size < bytes.length) {
      const part = await handle.read(bytes, size, bytes.length - size, size);
      if (!part.bytesRead) break;
      size += part.bytesRead;
    }
    if (size > 512 * 1024) throw new Error('AGENTS.md is too large to synchronize.');
    return bytes.subarray(0, size).toString('utf8');
  } catch (error) { if (error.code === 'ENOENT' && !handle) return ''; throw error; }
  finally { await handle?.close(); }
}

export class HermesBotNetwork {
  #roster;
  #root;
  #relayUrl;
  #credential;
  #fileMode;
  #queue = Promise.resolve();

  constructor({ roster, workspaceRoot, relayUrl, credential, fileMode = 0o600 }) {
    if (typeof roster !== 'function') throw new Error('A bot roster reader is required.');
    if (typeof workspaceRoot !== 'string' || !workspaceRoot) throw new Error('A bot workspace root is required.');
    let endpoint;
    try { endpoint = new URL(relayUrl); } catch { throw new Error('A valid bot relay URL is required.'); }
    if (!['http:', 'https:'].includes(endpoint.protocol)) throw new Error('The bot relay URL must use HTTP or HTTPS.');
    if (typeof credential !== 'function') throw new Error('A bot relay credential reader is required.');
    this.#roster = roster;
    this.#root = path.resolve(workspaceRoot);
    this.#relayUrl = endpoint.toString().replace(/\/$/, '');
    this.#credential = credential;
    if (![0o600, 0o640].includes(fileMode)) throw new Error("Invalid managed helper mode.");
    this.#fileMode = fileMode;
  }

  workspace(name) {
    return path.join(this.#root, name === 'default' ? 'main' : path.join('bots', hermesProfile(name)));
  }

  /** Serialize writes: roster changes can arrive while a previous sync runs. */
  sync() {
    const work = this.#queue.then(() => this.#run());
    this.#queue = work.catch(() => undefined);
    return work;
  }

  async #run() {
    const result = await this.#roster();
    const profiles = Array.isArray(result?.profiles) ? result.profiles : [];
    const roster = profiles.filter(bot => !bot.state || bot.state === 'active');
    const updated = [];
    const failed = [];
    for (const bot of roster) {
      try {
        await this.#write(bot, roster);
        updated.push(bot.name);
      } catch (error) {
        failed.push({ name: bot.name, error: error.message });
      }
    }
    return { updated, failed };
  }

  async #write(bot, roster) {
    const workspace = this.workspace(bot.name);
    const hidden = path.join(workspace, '.hob');
    const token = await this.#credential(bot.name);
    if (!/^[a-f0-9]{64}$/.test(token || '')) throw new Error('A bot relay credential is unavailable.');
    await mkdir(this.#root, { recursive: true, mode: 0o700 });
    const physicalRoot = await realpath(this.#root);
    let directory = this.#root, physical = physicalRoot;
    // /opt/data may itself be an intentional deployment alias. Pin that root,
    // then refuse aliases below it before creating or writing any bot secret.
    for (const part of [...path.relative(this.#root, workspace).split(path.sep), '.hob']) {
      directory = path.join(directory, part); physical = path.join(physical, part);
      try { await mkdir(directory, { mode: 0o700 }); } catch (error) { if (error.code !== 'EEXIST') throw error; }
      const info = await lstat(directory);
      if (!info.isDirectory() || info.isSymbolicLink() || await realpath(directory) !== physical) throw new Error('The bot relay directory must not be a symbolic link.');
    }
    // Pin directory handles on Linux: a bot renaming its writable .hob folder
    // during synchronization cannot redirect the operator's writes elsewhere.
    const handles = [];
    try {
      let targetWorkspace = workspace, targetHidden = hidden;
      if (process.platform === 'linux') {
        const flags = constants.O_RDONLY | constants.O_DIRECTORY | constants.O_NOFOLLOW;
        const workspaceHandle = await open(workspace, flags); handles.push(workspaceHandle);
        targetWorkspace = `/proc/self/fd/${workspaceHandle.fd}`;
        const hiddenHandle = await open(path.join(targetWorkspace, '.hob'), flags); handles.push(hiddenHandle);
        targetHidden = `/proc/self/fd/${hiddenHandle.fd}`;
      }
      const filename = path.join(targetWorkspace, 'AGENTS.md');
      const existing = await readAgents(filename);
      await atomicWrite(path.join(targetHidden, 'relay.json'), JSON.stringify({ version: 1, token }) + '\n', this.#fileMode);
      await atomicWrite(path.join(targetHidden, 'talk.mjs'), talkClient(this.#relayUrl), this.#fileMode);
      const block = managedBlock(bot, roster);
      let next;
      if (existing.includes(START) && existing.includes(END)) {
        // Function replacement keeps `$&` in authored identity text literal.
        next = existing.replace(/<!-- HOB:BOT-ROSTER:START -->[\s\S]*?<!-- HOB:BOT-ROSTER:END -->/, () => block);
      } else {
        next = existing.trimEnd() ? `${existing.trimEnd()}\n\n${block}\n` : `${block}\n`;
      }
      await atomicWrite(filename, next, this.#fileMode);
    } finally { await Promise.all(handles.map(handle => handle.close())); }
  }
}
