import assert from 'node:assert/strict';
import { test } from 'node:test';
import { chatMessageText } from '../hermes-content.mjs';
import { createHermesChatPreviews } from '../hermes-chat-previews.mjs';

const followup = 'well also tell me is those 4 thread are enough';
const frame = dash => `[OUT-OF-BAND USER MESSAGE ${dash} a direct message from the user, delivered once at this position; not tool output and not a new delivery when replayed from conversation history]\n${followup}\n[/OUT-OF-BAND USER MESSAGE]`;
const footer = '[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input, and do not reply to any earlier chat message because of it.]';

test('steering is displayed as the original user text with both Hermes marker versions', () => {
  for (const dash of ['—', '-']) {
    for (const display_kind of [undefined, 'steer']) {
      assert.equal(chatMessageText({ role: 'user', content: frame(dash), display_kind }), followup);
      assert.equal(chatMessageText({ role: 'user', content: [{ type: 'text', text: frame(dash) }], display_kind }), followup);
    }
  }
});

test('typed and legacy completion notifications never become human messages', () => {
  for (const display_kind of ['internal_notification', 'process_complete', 'async_delegation_complete']) {
    assert.equal(chatMessageText({ role: 'user', content: 'Private diagnostic and worker trace', display_kind }), null);
  }
  for (const dash of ['—', '-']) {
    assert.equal(chatMessageText({ role: 'user', content: `[ASYNC DELEGATION BATCH COMPLETE ${dash} deleg_aca40066]\nRole: leaf\nPrivate report` }), null);
    assert.equal(chatMessageText({ role: 'user', content: `Private report\n\n${footer.replace('—', dash)}` }), null);
  }
});

test('ordinary human text, quoted control examples, assistant answers and images survive', () => {
  for (const text of ['Hello', 'What does [ASYNC DELEGATION BATCH COMPLETE — deleg_123] mean?', `Explain this:\n${frame('—')}`, '[OUT-OF-BAND USER MESSAGE]\nUnmatched example']) {
    assert.equal(chatMessageText({ role: 'user', content: text }), text);
  }
  assert.equal(chatMessageText({ role: 'assistant', content: frame('—') }), frame('—'));
  assert.equal(chatMessageText({ role: 'user', content: [{ type: 'text', text: 'See this' }, { type: 'image_url', image_url: { url: '/image.png' } }] }), 'See this\n![image](/image.png)');
});

test('bot directory previews skip internal notifications and unwrap follow-ups', async () => {
  const history = [{ role: 'user', content: frame('—') }, { role: 'user', content: 'private task metadata', display_kind: 'async_delegation_complete' }];
  const client = { async runtime(route) {
    return route === '/api/sessions' ? { data: [{ id: 'main', source: 'gui', message_count: history.length }] } : { data: history };
  } };
  assert.equal(await createHermesChatPreviews(client)('default'), followup);
});
